// Shared price math, so the list, the detail page and the sort all agree: the discount is
// always computed from the two prices, never typed in twice.
export function pctOff(d) {
  return Math.round((1 - d.price / d.was) * 100);
}

export function saving(d) {
  return Math.round((d.was - d.price) * 100) / 100;
}

